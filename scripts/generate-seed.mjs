/**
 * Renders src/server/demo-jobs.json into migrations/0002_seed_demo_jobs.sql.
 *
 * The JSON file is the single source of truth for the demo dataset: the API
 * falls back to it when D1 is unavailable, and the migration seeds the same
 * rows into D1. Generating the SQL from the JSON keeps the two in step.
 *
 * Usage: npm run db:seed:generate
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const sourcePath = join(root, 'src', 'server', 'demo-jobs.json')
const targetPath = join(root, 'migrations', '0002_seed_demo_jobs.sql')

const { jobs } = JSON.parse(readFileSync(sourcePath, 'utf8'))

const sqlString = (value) => {
  if (value === null || value === undefined) return 'NULL'
  return `'${String(value).replace(/'/g, "''")}'`
}

const sqlList = (values) => sqlString(JSON.stringify(values))

const columns = [
  'id',
  'title',
  'company',
  'role_family',
  'seniority',
  'work_mode',
  'location_country',
  'location_label',
  'salary_min',
  'salary_max',
  'salary_currency',
  'salary_period',
  'description',
  'required_skills',
  'useful_skills',
  'eligible_countries',
  'sponsorship',
  'source_name',
  'source_url',
  'posted_days_ago',
  'is_demo',
]

const rows = jobs.map((job) => {
  const values = [
    sqlString(job.id),
    sqlString(job.title),
    sqlString(job.company),
    sqlString(job.roleFamily),
    sqlString(job.seniority),
    sqlString(job.workMode),
    sqlString(job.locationCountry),
    sqlString(job.locationLabel),
    job.salaryMin === null || job.salaryMin === undefined ? 'NULL' : String(job.salaryMin),
    job.salaryMax === null || job.salaryMax === undefined ? 'NULL' : String(job.salaryMax),
    sqlString(job.salaryCurrency),
    sqlString(job.salaryPeriod),
    sqlString(job.description),
    sqlList(job.requiredSkills),
    sqlList(job.usefulSkills),
    sqlList(job.eligibleCountries),
    sqlString(job.sponsorship),
    sqlString(job.sourceName),
    sqlString(job.sourceUrl),
    String(job.postedDaysAgo),
    job.isDemo ? '1' : '0',
  ]
  return `  (${values.join(', ')})`
})

const header = `-- Generated by scripts/generate-seed.mjs from src/server/demo-jobs.json.
-- Do not edit by hand: change the JSON and re-run "npm run db:seed:generate".
--
-- These are fictional roles on a fictional board. They are seeded so the
-- preview has something to rank and explain; they are not live vacancies and
-- must not be presented as such.
`

const statement = `INSERT OR REPLACE INTO jobs (${columns.join(', ')}) VALUES\n${rows.join(',\n')};`

writeFileSync(targetPath, `${header}\n${statement}\n`, 'utf8')

console.log(`Wrote ${jobs.length} demo roles to migrations/0002_seed_demo_jobs.sql`)
