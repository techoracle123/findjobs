import type { CvSuggestion, Seniority, WorkMode } from '../shared/types'
import {
  ROLE_FAMILY_KEYWORDS,
  SENIORITY_KEYWORDS,
  SKILL_CATALOGUE,
  WORK_MODE_KEYWORDS,
} from '../shared/skills'
import type { AiBinding } from './env'

const SENIORITY_RANK: Record<string, number> = {
  intern: 0,
  junior: 1,
  mid: 2,
  senior: 3,
  staff: 4,
  lead: 5,
  principal: 6,
}

function countMatches(text: string, patterns: RegExp[]): number {
  let count = 0
  for (const pattern of patterns) {
    const flags = pattern.flags.includes('g') ? pattern.flags : `${pattern.flags}g`
    const matches = text.match(new RegExp(pattern.source, flags))
    if (matches) count += matches.length
  }
  return count
}

/**
 * Deterministic keyword extraction. This is the fallback used whenever the
 * Workers AI binding is absent, and it is also what the local preview always
 * uses. It is intentionally simple and explainable: it reports which patterns
 * matched rather than inventing a profile.
 */
export function suggestFromKeywords(text: string): CvSuggestion {
  const haystack = text.toLowerCase()

  const scored = SKILL_CATALOGUE.map((entry) => ({
    label: entry.label,
    hits: countMatches(haystack, entry.patterns),
    weight: entry.weight,
  }))
    .filter((entry) => entry.hits > 0)
    .sort((a, b) => b.hits * b.weight - a.hits * a.weight || a.label.localeCompare(b.label))

  const skills = scored.slice(0, 14).map((entry) => entry.label)

  const roleFamilies = ROLE_FAMILY_KEYWORDS.filter((entry) =>
    entry.patterns.some((pattern) => pattern.test(haystack)),
  ).map((entry) => entry.family)

  const seniority = SENIORITY_KEYWORDS.filter((entry) =>
    entry.patterns.some((pattern) => pattern.test(haystack)),
  )
    .map((entry) => entry.level)
    .sort((a, b) => (SENIORITY_RANK[b] ?? 0) - (SENIORITY_RANK[a] ?? 0))

  const workModes = WORK_MODE_KEYWORDS.filter((entry) =>
    entry.patterns.some((pattern) => pattern.test(haystack)),
  ).map((entry) => entry.mode as WorkMode)

  const notes: string[] = []
  if (skills.length === 0) {
    notes.push('No catalogue skills were detected. Try a CV with a skills section.')
  }
  if (roleFamilies.length === 0) {
    notes.push('No role family was detected, so the results are ranked on skills alone.')
  }
  if (workModes.length === 0) {
    notes.push('No work mode was detected, so eligibility filtering stays broad.')
  }

  const top = scored.slice(0, 3).map((entry) => entry.label)
  const summary =
    top.length > 0
      ? `Detected ${skills.length} skills, strongest in ${top.join(', ')}.`
      : 'No skills were detected in the supplied text.'

  return {
    skills,
    roleFamilies,
    seniority: seniority.slice(0, 2) as Seniority[],
    workModes,
    summary,
    provider: 'keyword-fallback',
    notes,
  }
}

function extractJsonBlock(raw: string): string {
  const fenced = raw.match(/```(?:json)?\s*([\s\S]*?)```/)
  const candidate = fenced ? fenced[1] : raw
  const start = candidate.indexOf('{')
  const end = candidate.lastIndexOf('}')
  if (start === -1 || end === -1 || end <= start) throw new Error('no JSON object in model output')
  return candidate.slice(start, end + 1)
}

/**
 * Workers AI path. It is only used when an `AI` binding is actually
 * configured; the local preview deliberately leaves that binding unset.
 */
export async function suggestWithAi(ai: AiBinding, text: string): Promise<CvSuggestion> {
  const prompt = [
    'Extract a job-search profile from the CV text below.',
    'Reply with JSON only, using exactly this shape:',
    '{"skills":["..."],"roleFamilies":["frontend|backend|fullstack|data|ml|platform|devops|security|product|design|qa|mobile"],"seniority":["intern|junior|mid|senior|staff|lead|principal"],"workModes":["remote|hybrid|onsite"],"summary":"one sentence"}',
    '',
    text.slice(0, 12_000),
  ].join('\n')

  const response = (await ai.run('@cf/meta/llama-3.1-8b-instruct', {
    messages: [
      { role: 'system', content: 'You extract structured job-search profiles from CVs.' },
      { role: 'user', content: prompt },
    ],
  })) as { response?: string }

  const raw = response?.response ?? ''
  const parsed = JSON.parse(extractJsonBlock(raw)) as Partial<CvSuggestion>

  return {
    skills: Array.isArray(parsed.skills) ? parsed.skills.map(String).slice(0, 20) : [],
    roleFamilies: Array.isArray(parsed.roleFamilies) ? parsed.roleFamilies.map(String) : [],
    seniority: Array.isArray(parsed.seniority) ? (parsed.seniority as Seniority[]) : [],
    workModes: Array.isArray(parsed.workModes) ? (parsed.workModes as WorkMode[]) : [],
    summary: typeof parsed.summary === 'string' ? parsed.summary : '',
    provider: 'workers-ai',
    notes: ['Generated by the Workers AI binding. Review the suggestions before using them.'],
  }
}

export async function suggest(
  ai: AiBinding | undefined,
  text: string,
): Promise<CvSuggestion> {
  if (ai) {
    try {
      return await suggestWithAi(ai, text)
    } catch {
      const fallback = suggestFromKeywords(text)
      return {
        ...fallback,
        notes: [...fallback.notes, 'The AI binding was enabled but the request failed, so keyword extraction was used.'],
      }
    }
  }
  return suggestFromKeywords(text)
}
