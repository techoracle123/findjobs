import type { CvSuggestion, Seniority, WorkMode } from '../shared/types'
import type { AiBinding, Env } from './env'
import { openRouterJson } from './openrouter'
import { ROLE_FAMILIES, SENIORITIES, WORK_MODES } from '../shared/taxonomy'
import { cleanJobText } from './sources/html'
import { suggestFromKeywords } from '../shared/cv-suggest'

export { suggestFromKeywords }

function extractJsonBlock(raw: string): string {
  const fenced = raw.match(/```(?:json)?\s*([\s\S]*?)```/)
  const candidate = fenced ? fenced[1] : raw
  const start = candidate.indexOf('{')
  const end = candidate.lastIndexOf('}')
  if (start === -1 || end === -1 || end <= start) throw new Error('no JSON object in model output')
  return candidate.slice(start, end + 1)
}

/**
 * Workers AI path. It is only used when an `AI` binding is actually
 * configured; the local preview deliberately leaves that binding unset.
 */
export async function suggestWithAi(ai: AiBinding, text: string): Promise<CvSuggestion> {
  const prompt = [
    'Extract a job-search profile from the CV text below.',
    'Reply with JSON only, using exactly this shape:',
    '{"skills":["..."],"roleFamilies":["' +
      ROLE_FAMILIES.join('|') +
      '"],"seniority":["intern|junior|mid|senior|staff|lead|principal"],"workModes":["remote|hybrid|onsite"],"summary":"one sentence"}',
    '',
    text.slice(0, 12_000),
  ].join('\n')

  const response = (await ai.run('@cf/meta/llama-3.1-8b-instruct', {
    messages: [
      { role: 'system', content: 'You extract structured job-search profiles from CVs.' },
      { role: 'user', content: prompt },
    ],
  })) as { response?: string }

  const raw = response?.response ?? ''
  const parsed = JSON.parse(extractJsonBlock(raw)) as Partial<CvSuggestion>

  return {
    skills: Array.isArray(parsed.skills) ? parsed.skills.map(String).slice(0, 20) : [],
    roleFamilies: Array.isArray(parsed.roleFamilies) ? parsed.roleFamilies.map(String) : [],
    seniority: Array.isArray(parsed.seniority) ? (parsed.seniority as Seniority[]) : [],
    workModes: Array.isArray(parsed.workModes) ? (parsed.workModes as WorkMode[]) : [],
    summary: typeof parsed.summary === 'string' ? parsed.summary : '',
    provider: 'workers-ai',
    notes: ['Generated by the Workers AI binding. Review the suggestions before using them.'],
  }
}

export async function suggest(
  ai: AiBinding | undefined,
  text: string,
  env?: Env,
): Promise<CvSuggestion> {
  if (env?.OPENROUTER_API_KEY) {
    try {
      const parsed = await openRouterJson(
        env,
        `Extract a job-search profile from this CV. Return {"skills":["..."],"roleFamilies":["..."],"seniority":["..."],"workModes":["..."],"summary":"one sentence"}. Only extract stated facts. Valid role families: ${ROLE_FAMILIES.join(', ')}. Seniority: ${SENIORITIES.join(', ')}. Work modes: ${WORK_MODES.join(', ')}.`,
        { text: text.slice(0, 12000) },
      )
      const list = (value: unknown) =>
        Array.isArray(value)
          ? value
              .filter((item): item is string => typeof item === 'string')
              .map((item) => cleanJobText(item).slice(0, 80))
              .slice(0, 20)
          : []
      return {
        skills: list(parsed.skills),
        roleFamilies: list(parsed.roleFamilies).filter((item) =>
          ROLE_FAMILIES.includes(item as (typeof ROLE_FAMILIES)[number]),
        ),
        seniority: list(parsed.seniority).filter((item) =>
          SENIORITIES.includes(item as Seniority),
        ) as Seniority[],
        workModes: list(parsed.workModes).filter((item) =>
          WORK_MODES.includes(item as WorkMode),
        ) as WorkMode[],
        summary:
          typeof parsed.summary === 'string' ? cleanJobText(parsed.summary).slice(0, 400) : '',
        provider: 'openrouter',
        notes: ['AI suggestions from OpenRouter. Review them before adding to your profile.'],
      }
    } catch {
      return {
        ...suggestFromKeywords(text),
        notes: ['OpenRouter is temporarily unavailable. Local keyword matching was used instead.'],
      }
    }
  }
  if (ai) {
    try {
      return await suggestWithAi(ai, text)
    } catch {
      const fallback = suggestFromKeywords(text)
      return {
        ...fallback,
        notes: [
          ...fallback.notes,
          'The AI binding was enabled but the request failed, so keyword extraction was used.',
        ],
      }
    }
  }
  return suggestFromKeywords(text)
}
