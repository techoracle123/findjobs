import type { IdeaFormat, IdeaRoute } from '../../shared/ideas'

export interface IdeaConcept {
  id: string
  categoryId: string
  title: string
  format: IdeaFormat
  route: IdeaRoute
  buyer: string
  product: string
  firstVersion: string
  revenueModel: string
  testWindow: string
  keywords: string[]
}

export interface IdeaCategory {
  id: string
  label: string
  indicatorId: string
  unit: 'percent' | 'per_1000' | 'pm25'
  direction: 'lower_access' | 'higher_pressure'
  scaleMax: number
  problem: string
  interpretation: string
  validationFocus: string
  skills: string[]
  risks: string[]
}

function product(
  categoryId: string,
  id: string,
  title: string,
  format: IdeaFormat,
  route: IdeaRoute,
  buyer: string,
  offer: string,
  firstVersion: string,
  revenueModel: string,
  keywords: string,
): IdeaConcept {
  return {
    id: `${categoryId}-${id}`,
    categoryId,
    title,
    format,
    route,
    buyer,
    product: offer,
    firstVersion,
    revenueModel,
    testWindow: format === 'software' ? '7 days' : format === 'hybrid' ? '21 days' : '14 days',
    keywords: keywords.split(' '),
  }
}

function category(
  definition: IdeaCategory,
  products: IdeaConcept[],
): IdeaCategory & { products: IdeaConcept[] } {
  if (products.length !== 12 || products.some((item) => item.categoryId !== definition.id)) {
    throw new Error(`Idea category ${definition.id} must contain exactly 12 matching products`)
  }
  return { ...definition, products }
}

